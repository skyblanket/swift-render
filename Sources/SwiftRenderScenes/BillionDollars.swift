    // MARK: - 04 · log(500, 1.93) ≈ 9.45  (the money shot)

    @MainActor static func calcLog(_ t: Double) -> some View {
        let k     = Ease.easeOut(Ease.clip(t, 0.0, 0.7))
        let mult  = Ease.easeOutBack(Ease.clip(t, 1.2, 2.2))
