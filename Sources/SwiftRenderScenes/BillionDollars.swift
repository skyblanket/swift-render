                    Image(systemName: "magnifyingglass")
                        .font(.system(size: 30, weight: .medium)).foregroundStyle(dim)
                    Text(shown + caret)
                        .font(.system(size: 44, weight: .semibold, design: .monospaced))
                        .foregroundStyle(ink)
