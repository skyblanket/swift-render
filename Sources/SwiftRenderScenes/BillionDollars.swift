    // MARK: - 08 · Tell their friends (viral spread)

    @MainActor static func tellFriends(_ t: Double) -> some View {
        let k = Ease.easeOut(Ease.clip(t, 0.0, 0.7))
        let cap = Ease.easeOut(Ease.clip(t, 7.4, 8.6))
        return ZStack {
            kicker("HOW YOU GET THE GROWTH RATE", k)
                .frame(maxHeight: .infinity, alignment: .top).padding(.top, 120)
            // three generations of branching dots
            ZStack {
                spreadNode(t, gen: 0, idx: 0, count: 1, start: 0.7)
                ForEach(0..<3, id: \.self) { i in spreadNode(t, gen: 1, idx: i, count: 3, start: 1.6) }
                ForEach(0..<9, id: \.self) { i in spreadNode(t, gen: 2, idx: i, count: 9, start: 2.8) }
            }
            .frame(width: 1400, height: 560)
            Text("make something so good they tell their friends")
                .font(.custom("Inter-Bold", size: 46)).foregroundStyle(ink)
                .opacity(cap)
                .frame(maxHeight: .infinity, alignment: .bottom).padding(.bottom, 110)
        }
    }

    @ViewBuilder static func spreadNode(_ t: Double, gen: Int, idx: Int, count: Int, start: Double) -> some View {
        let p = Ease.easeOutBack(Ease.clip(t, start + Double(idx) * 0.05, start + 0.5 + Double(idx) * 0.05))
        let y = CGFloat(gen) * 180 - 180
        let spanW: CGFloat = gen == 0 ? 0 : (gen == 1 ? 760 : 1240)
        let x = count == 1 ? 0 : (CGFloat(idx) / CGFloat(count - 1) - 0.5) * spanW
        let c = gen == 0 ? Self.accent : (gen == 1 ? Self.ink : Self.dim)
        let size: CGFloat = gen == 0 ? 46 : (gen == 1 ? 30 : 20)
        Circle().fill(c).frame(width: size, height: size)
            .shadow(color: c.opacity(0.6), radius: gen == 0 ? 16 : 6)
            .scaleEffect(p).opacity(p)
            .offset(x: x, y: y)
    }

