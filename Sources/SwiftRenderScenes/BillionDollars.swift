import SwiftUI
import SwiftRender

/// BillionDollars — an animated, narrated explainer of Paul Graham's essay
/// "How to Earn a Billion Dollars" (June 2026).
///
/// Fourteen chapters on a shared `anchors` grid. Each chapter is a pure
/// function of local time that *illustrates* a beat of the argument — the
/// 93%-a-month founder, log(500, 1.93) ≈ 9.45, 1.15^60 ≈ 4384, the two
/// numbers, "ideas sound lame", Justin.TV → Twitch — rather than just
/// captioning it. A synthesized ambient score is declared next to the same
/// `anchors` array, so music can't drift from picture.
///
/// Kokoro TTS narration is layered on at render time — `durs` below is
/// generated from the measured VO length by `tools/billion_vo.py`, and the
/// VO start times mirror `anchors`. One command does the whole pipeline:
///
///   bash tools/make_billion_audio.sh        # Kokoro VO → mix → render
///   swift run swift-render render BillionDollars --out out/billion.mp4   # silent picture + score
public struct BillionDollars: RenderScene {
    // 14 chapter lengths (s). GENERATED by tools/billion_vo.py — keep in sync.
    static let durs: [Double] = [6.2, 13.2, 17.3, 14.2, 20.5, 18.4, 16, 17.2, 11.8, 15.2, 16.6, 14.9, 12.6, 13.7]
    static let cross: Double = 0.5   // crossfade overlap between chapters

    /// Absolute start of each chapter. anchors[i+1] = anchors[i] + durs[i] - cross.
    static let anchors: [Double] = {
        var out: [Double] = []; var c = 0.0
        for d in durs { out.append(c); c += d - cross }
        return out
    }()

    public static let defaultDuration: Double = anchors.last! + durs.last!   // ≈ 201.3s

    // MARK: palette
    static let bg     = Color(red: 0.039, green: 0.039, blue: 0.047)
    static let ink    = Color(red: 0.961, green: 0.949, blue: 0.925)
    static let dim    = Color(red: 0.56,  green: 0.57,  blue: 0.60)
    static let faint  = Color(red: 0.30,  green: 0.31,  blue: 0.34)
    static let accent = Color(red: 0.776, green: 1.0,   blue: 0.102)   // #C7FF1A volt
    static let gold   = Color(red: 1.0,   green: 0.784, blue: 0.341)   // #FFC857 money
    static let warn   = Color(red: 0.949, green: 0.471, blue: 0.361)   // #F2785C
    static let panel  = Color(white: 0.075)

    // MARK: - Body

    @MainActor public static func body(at t: Double, duration: Double) -> some View {
        let a = anchors
        return ZStack {
            bg.ignoresSafeArea()
            Timeline(t) {
                Clip(at: a[0],  for: durs[0])  { l in wrap(l, durs[0])  { titleCard(l) } }
                Clip(at: a[1],  for: durs[1])  { l in wrap(l, durs[1])  { theClaim(l) } }
                Clip(at: a[2],  for: durs[2])  { l in wrap(l, durs[2])  { theFounder(l) } }
                Clip(at: a[3],  for: durs[3])  { l in wrap(l, durs[3])  { theObjection(l) } }
                Clip(at: a[4],  for: durs[4])  { l in wrap(l, durs[4])  { calcLog(l) } }
                Clip(at: a[5],  for: durs[5])  { l in wrap(l, durs[5])  { calcCompound(l) } }
                Clip(at: a[6],  for: durs[6])  { l in wrap(l, durs[6])  { exponentialMagic(l) } }
                Clip(at: a[7],  for: durs[7])  { l in wrap(l, durs[7])  { twoNumbers(l) } }
                Clip(at: a[8],  for: durs[8])  { l in wrap(l, durs[8])  { tellFriends(l) } }
                Clip(at: a[9],  for: durs[9])  { l in wrap(l, durs[9])  { predictDemand(l) } }
                Clip(at: a[10], for: durs[10]) { l in wrap(l, durs[10]) { ideasSoundLame(l) } }
                Clip(at: a[11], for: durs[11]) { l in wrap(l, durs[11]) { twitch(l) } }
                Clip(at: a[12], for: durs[12]) { l in wrap(l, durs[12]) { empathy(l) } }
                Clip(at: a[13], for: durs[13]) { l in wrap(l, durs[13]) { lockup(l) } }
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    /// Score lives next to the Timeline: `anchors` drives both cuts and hits.
    public static func soundtrack(duration: Double) -> Score? {
        let cuts = Array(anchors.dropFirst())
        return Score(duration: duration) {
            drone(.a1, from: 0, for: duration, amp: 0.075)
            drone(.e2, from: anchors[6], for: 95, amp: 0.03)
            boom(at: 0.2, amp: 0.45, duration: 2.4)
            crashes(at: cuts, amp: 0.11)
            // calc reveals — a hit lands when the number lands
            boom(at: anchors[4] + 10.6,  amp: 0.4, duration: 2.0)     // log(500,1.93) ≈ 9.45
            boom(at: anchors[5] + 9.8,   amp: 0.4, duration: 2.0)     // ×4384
            // momentum into the thesis slide
            every(1.0, from: anchors[7], to: anchors[7] + 6) { kick(at: $0, amp: 0.2) }
            boom(at: anchors[13], amp: 0.7, duration: 3.0)            // lockup finale
        }
    }


    // MARK: - Shared building blocks

    /// Per-chapter crossfade: up over the first `cross`, down over the last.
    @ViewBuilder @MainActor
    static func wrap<V: View>(_ l: Double, _ dur: Double, @ViewBuilder _ content: () -> V) -> some View {
        let fin = Ease.easeInOut(Ease.clip(l, 0, cross))
        let fout = 1 - Ease.easeInOut(Ease.clip(l, dur - cross, dur))
        content()
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .opacity(fin * fout)
    }

    /// Small mono uppercase kicker label with an accent tick.
    @ViewBuilder
    static func kicker(_ text: String, _ p: Double, color: Color = accent) -> some View {
        HStack(spacing: 12) {
            Rectangle().fill(color).frame(width: 22, height: 3)
            Text(text)
                .font(.system(size: 22, weight: .semibold, design: .monospaced))
                .tracking(4)
                .foregroundStyle(color)
        }
        .opacity(p)
        .offset(x: (1 - p) * -24)
    }

    /// A line that wipes up behind a moving mask.
    @ViewBuilder
    static func reveal<V: View>(_ p: Double, height: CGFloat, @ViewBuilder _ content: () -> V) -> some View {
        content()
            .opacity(p)
            .mask(Rectangle().frame(height: CGFloat(p) * height).frame(maxHeight: .infinity, alignment: .top))
    }

    /// Marker orbiting the center of a 2R box at `angleDeg`.
    @ViewBuilder
    static func orbit<V: View>(radius R: CGFloat, angleDeg: Double, @ViewBuilder _ child: () -> V) -> some View {
        ZStack { child().offset(x: R) }
            .frame(width: 2 * R, height: 2 * R)
            .rotationEffect(.degrees(angleDeg))
    }

    /// Exponential curve from (0,h) climbing to the top-right, drawn 0→p.
    @ViewBuilder
    static func expCurve(_ p: Double, w: CGFloat, h: CGFloat, k: Double,
                         color: Color, lineWidth: CGFloat = 5) -> some View {
        let maxY = exp(k) - 1
        Path { path in
            path.move(to: CGPoint(x: 0, y: h))
            let n = 150
            for i in 0...n {
                let x = Double(i) / Double(n)
                let yy = (exp(k * x) - 1) / maxY            // 0…1
                path.addLine(to: CGPoint(x: CGFloat(x) * w, y: h - CGFloat(yy) * h))
            }
        }
        .trim(from: 0, to: p)
        .stroke(color, style: StrokeStyle(lineWidth: lineWidth, lineCap: .round, lineJoin: .round))
        .frame(width: w, height: h)
    }

    static func hash01(_ x: Double) -> Double {
        abs((sin(x) * 43758.5453).truncatingRemainder(dividingBy: 1.0))
    }

