        let shown = String(formula.prefix(typed))
        let caret = typeP < 1 ? "▌" : ""
        let resP  = Ease.easeOutBack(Ease.clip(t, 9.6, 10.8))    // = 9.45
        let lineP = Ease.easeInOut(Ease.clip(t, 12.2, 14.0))     // number line draws
