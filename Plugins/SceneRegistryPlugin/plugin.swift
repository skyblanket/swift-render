import Foundation
import PackagePlugin

/// Generates `SceneRegistry.swift` for an executable target by scanning it and
/// its same-package source-module dependencies for `public struct X: <SceneProtocol>`.
/// Adding a scene file is the only step — no hand-edited dictionary.
///
/// Works for this repo (`swift-render` scans `SwiftRender`) and for any package
/// that applies the plugin to its own CLI target:
///
///     .executableTarget(name: "launch", dependencies: ["LaunchScenes",
///         .product(name: "SwiftRenderTool", package: "swift-render")],
///         plugins: [.plugin(name: "SceneRegistryPlugin", package: "swift-render")])
@main
struct SceneRegistryPlugin: BuildToolPlugin {
    static let protocols: Set<String> = ["RenderScene", "AudioReactiveScene", "PropsScene", "PropsAudioScene"]

    func createBuildCommands(context: PluginContext, target: Target) async throws -> [Command] {
        guard let exe = target as? SourceModuleTarget else { return [] }
        var modules: [SourceModuleTarget] = []
        for dep in target.dependencies {
            if case .target(let t) = dep, let s = t as? SourceModuleTarget, s.kind == .generic {
                modules.append(s)
            }
        }
        modules.append(exe)

        let decl = try NSRegularExpression(pattern: #"public\s+struct\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*([^{]+)\{"#)
        var found: [(name: String, module: String, file: String)] = []
        var inputs: [Path] = []
        for module in modules {
            let files = module.sourceFiles(withSuffix: "swift").map(\.path).sorted { $0.string < $1.string }
            inputs += files
            for file in files {
                guard let src = try? String(contentsOfFile: file.string, encoding: .utf8) else { continue }
                let ns = src as NSString
                for m in decl.matches(in: src, range: NSRange(location: 0, length: ns.length)) {
                    let name = ns.substring(with: m.range(at: 1))
                    let clause = ns.substring(with: m.range(at: 2))
                    let conforms = clause.split(whereSeparator: { ",: \n\t".contains($0) }).map(String.init)
                    if conforms.contains(where: Self.protocols.contains) {
                        found.append((name, module.moduleName, file.string))
                    }
                }
            }
        }
        var seen = Set<String>()
        found = found.filter { seen.insert($0.name).inserted }.sorted { $0.name < $1.name }

        let imports = Set(found.map(\.module)).subtracting([exe.moduleName]).sorted()
            .map { "import \($0)" }.joined(separator: "\n")
        let body = found.map {
            "    \"\($0.name)\": SceneRunner(\($0.name).self).source(\(literal($0.file))),"
        }.joined(separator: "\n")
        let source = """
        // Generated by SceneRegistryPlugin — do not edit.
        import SwiftRenderTool
        \(imports)

        @MainActor let generatedSceneRunners: [String: SceneRunner] = [
        \(body.isEmpty ? "    :" : body)
        ]

        """
        let out = context.pluginWorkDirectory.appending("SceneRegistry.swift")
        return [.buildCommand(
            displayName: "Generating scene registry (\(found.count) scenes)",
            executable: Path("/bin/sh"),
            arguments: ["-c", "printf '%s' \"$1\" > \"$2\"", "sh", source, out.string],
            inputFiles: inputs,
            outputFiles: [out]
        )]
    }

    private func literal(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
